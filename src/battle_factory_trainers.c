// The BATTLE FACTORY's opponents: Emerald's three hundred frontier trainers,
// carrying only their class and their name.
//
// Emerald's entries also hold three six-word easy-chat speeches each, which is
// most of the two and a half thousand lines the original table runs to. None
// of it is reachable here -- the speeches are spoken by frontier dialogue code
// that is not part of this port -- so they are left behind and the struct is
// the two fields the factory actually reads: the class picks the overworld
// sprite, and the name goes on the battle screen.
//
// The order and the count are Emerald's, deliberately: GetRandomScaledFrontier
// TrainerId draws from fixed index ranges that get harder the deeper the run
// goes, and those ranges only mean anything against this table in this order.
//
